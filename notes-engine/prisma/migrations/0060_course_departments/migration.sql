-- Courses by department and level (docs/engineering_courses.xlsx, LASU Faculty of
-- Engineering, First Semester 2026/2027). Onboarding gives a student their class's
-- courses straight away (400 Level ECE gets the 400 Level ECE list), so nobody
-- scrolls the whole faculty list. A shared course is listed under every class that
-- takes it. Department is the department CODE (ECE, MEE, ...), so renaming a
-- department never breaks the link. Status: C compulsory, R required, E elective
-- (blank in the sheet counts as C).
CREATE TABLE IF NOT EXISTS course_departments (
  course TEXT NOT NULL REFERENCES courses(code) ON DELETE CASCADE ON UPDATE CASCADE,
  department TEXT NOT NULL,
  level TEXT NOT NULL,
  semester TEXT NOT NULL DEFAULT 'First Semester',
  status TEXT NOT NULL DEFAULT 'C' CHECK (status IN ('C','R','E')),
  PRIMARY KEY (course, department, level)
);
CREATE INDEX IF NOT EXISTS course_departments_class_idx ON course_departments (department, level);
ALTER TABLE course_departments ENABLE ROW LEVEL SECURITY;

